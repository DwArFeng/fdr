package com.dwarfeng.fdr.sdk.bean.entity;

import com.alibaba.fastjson.annotation.JSONField;
import com.dwarfeng.fdr.stack.bean.entity.FetcherSupport;
import com.dwarfeng.subgrade.sdk.bean.key.FastJsonStringIdKey;
import com.dwarfeng.subgrade.stack.bean.Bean;

import java.util.Objects;

/**
 * FastJson 抓取器支持。
 *
 * @author DwArFeng
 * @since 3.1.0
 */
public class FastJsonFetcherSupport implements Bean {

    private static final long serialVersionUID = -1215321544937650951L;

    public static FastJsonFetcherSupport of(FetcherSupport fetcherSupport) {
        if (Objects.isNull(fetcherSupport)) {
            return null;
        } else {
            return new FastJsonFetcherSupport(
                    FastJsonStringIdKey.of(fetcherSupport.getKey()),
                    fetcherSupport.getLabel(),
                    fetcherSupport.getDescription(),
                    fetcherSupport.getExampleParam()
            );
        }
    }

    @JSONField(name = "key", ordinal = 1)
    private FastJsonStringIdKey key;

    @JSONField(name = "label", ordinal = 2)
    private String label;

    @JSONField(name = "description", ordinal = 3)
    private String description;

    @JSONField(name = "example_param", ordinal = 4)
    private String exampleParam;

    public FastJsonFetcherSupport() {
    }

    public FastJsonFetcherSupport(
            FastJsonStringIdKey key, String label, String description, String exampleParam
    ) {
        this.key = key;
        this.label = label;
        this.description = description;
        this.exampleParam = exampleParam;
    }

    public FastJsonStringIdKey getKey() {
        return key;
    }

    public void setKey(FastJsonStringIdKey key) {
        this.key = key;
    }

    public String getLabel() {
        return label;
    }

    public void setLabel(String label) {
        this.label = label;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getExampleParam() {
        return exampleParam;
    }

    public void setExampleParam(String exampleParam) {
        this.exampleParam = exampleParam;
    }

    @Override
    public String toString() {
        return "FastJsonFetcherSupport{" +
                "key=" + key +
                ", label='" + label + '\'' +
                ", description='" + description + '\'' +
                ", exampleParam='" + exampleParam + '\'' +
                '}';
    }
}
